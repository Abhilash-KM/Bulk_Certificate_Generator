from pathlib import Path

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.pdfgen import canvas

from app.models import GenerationJob, Recipient


GENERATED_DIR = Path("generated")
GENERATED_DIR.mkdir(exist_ok=True)


def draw_certificate_template(
    pdf: canvas.Canvas,
    width: float,
    height: float,
) -> None:
    """Draw the reusable certificate template."""

    # Outer border
    pdf.setStrokeColor(colors.HexColor("#1F3A5F"))
    pdf.setLineWidth(3)
    pdf.rect(35, 35, width - 70, height - 70)

    # Inner border
    pdf.setStrokeColor(colors.HexColor("#C9A227"))
    pdf.setLineWidth(1)
    pdf.rect(45, 45, width - 90, height - 90)

    # Header
    pdf.setFillColor(colors.HexColor("#1F3A5F"))
    pdf.setFont("Helvetica-Bold", 28)
    pdf.drawCentredString(
        width / 2,
        height - 125,
        "CERTIFICATE OF COMPLETION",
    )

    # Decorative line
    pdf.setStrokeColor(colors.HexColor("#C9A227"))
    pdf.setLineWidth(2)
    pdf.line(
        width / 2 - 150,
        height - 145,
        width / 2 + 150,
        height - 145,
    )

    pdf.setFillColor(colors.HexColor("#555555"))
    pdf.setFont("Helvetica", 13)
    pdf.drawCentredString(
        width / 2,
        height - 185,
        "This certificate is proudly presented to",
    )


def generate_certificate(
    job: GenerationJob,
    recipient: Recipient,
) -> str:
    """Generate a certificate using the predefined template."""

    file_name = f"certificate_{recipient.id}.pdf"
    file_path = GENERATED_DIR / file_name

    pdf = canvas.Canvas(str(file_path), pagesize=A4)
    width, height = A4

    # Draw reusable template
    draw_certificate_template(pdf, width, height)

    # Recipient name
    pdf.setFillColor(colors.HexColor("#1F3A5F"))
    pdf.setFont("Helvetica-Bold", 30)
    pdf.drawCentredString(
        width / 2,
        height - 245,
        recipient.name,
    )

    # Course
    pdf.setFillColor(colors.HexColor("#333333"))
    pdf.setFont("Helvetica", 15)
    pdf.drawCentredString(
        width / 2,
        height - 290,
        "for successfully completing",
    )

    pdf.setFont("Helvetica-Bold", 20)
    pdf.setFillColor(colors.HexColor("#1F3A5F"))
    pdf.drawCentredString(
        width / 2,
        height - 325,
        recipient.course,
    )

    # Event
    pdf.setFillColor(colors.HexColor("#444444"))
    pdf.setFont("Helvetica", 13)
    pdf.drawCentredString(
        width / 2,
        height - 380,
        f"Event: {job.event_name}",
    )

    # Completion date
    pdf.drawCentredString(
        width / 2,
        height - 405,
        f"Completion Date: {recipient.completion_date}",
    )

    # Footer
    pdf.setFillColor(colors.HexColor("#777777"))
    pdf.setFont("Helvetica", 10)
    pdf.drawCentredString(
        width / 2,
        75,
        "Generated by Bulk Certificate Generator",
    )

    pdf.showPage()
    pdf.save()

    return str(file_path)